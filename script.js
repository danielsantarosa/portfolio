function typeRole() {
  const role = roles[currentLanguage][roleIndex];
  typedRole.textContent = deleting ? role.slice(0, charIndex--) : role.slice(0, charIndex++);
  let speed = deleting ? 32 : 58;
  if (!deleting && charIndex > role.length) { deleting = true; speed = 1800; }
  else if (deleting && charIndex < 0) { deleting = false; roleIndex = (roleIndex + 1) % roles[currentLanguage].length; charIndex = 0; speed = 350; }
  typeTimer = setTimeout(typeRole, speed);
}

