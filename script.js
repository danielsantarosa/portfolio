const canvas = document.getElementById("particle-canvas");
const ctx = canvas.getContext("2d");
let particles = [];
let pointer = { x: -1000, y: -1000 };
function resizeCanvas() {
  const dpr = Math.min(window.devicePixelRatio || 1, 2);
  canvas.width = innerWidth * dpr; canvas.height = innerHeight * dpr;
  canvas.style.width = `${innerWidth}px`; canvas.style.height = `${innerHeight}px`;
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  const count = Math.min(95, Math.floor(innerWidth / 16));
  particles = Array.from({ length: count }, () => ({ x: Math.random() * innerWidth, y: Math.random() * innerHeight, vx: (Math.random() - .5) * .22, vy: (Math.random() - .5) * .22, r: Math.random() * 1.3 + .4 }));
}
function drawParticles() {
  ctx.clearRect(0, 0, innerWidth, innerHeight);
  particles.forEach((particle, index) => {
    particle.x += particle.vx; particle.y += particle.vy;
    if (particle.x < 0 || particle.x > innerWidth) particle.vx *= -1;
    if (particle.y < 0 || particle.y > innerHeight) particle.vy *= -1;
    const dxMouse = particle.x - pointer.x, dyMouse = particle.y - pointer.y;
    const mouseDistance = Math.hypot(dxMouse, dyMouse);
    if (mouseDistance < 130 && mouseDistance > 0) {
      particle.x += (dxMouse / mouseDistance) * .35;
      particle.y += (dyMouse / mouseDistance) * .35;
    }
    ctx.beginPath(); ctx.arc(particle.x, particle.y, particle.r, 0, Math.PI * 2);
    ctx.fillStyle = "rgba(23,20,15,.28)"; ctx.fill();
    for (let j = index + 1; j < particles.length; j++) {
      const other = particles[j];
      const distance = Math.hypot(particle.x - other.x, particle.y - other.y);
      if (distance < 105) {
        ctx.beginPath(); ctx.moveTo(particle.x, particle.y); ctx.lineTo(other.x, other.y);
        ctx.strokeStyle = `rgba(23,20,15,${.055 * (1 - distance / 105)})`;
        ctx.stroke();
      }
    }
  });
  requestAnimationFrame(drawParticles);
}
